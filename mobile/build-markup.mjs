// Rebuild committed, same-origin browser assets from the locked dev dependencies.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url)), out = join(here, 'web/vendor');
mkdirSync(join(out, 'fonts'), { recursive: true });
await build({ stdin: { contents: "export { default as MarkdownIt } from 'markdown-it'; export { default as katex } from 'katex';", resolveDir: here }, outfile: join(out, 'markdown-engine.js'), bundle: true, minify: true, format: 'esm', platform: 'browser', target: ['es2020'], legalComments: 'inline' });
const katex = join(here, 'node_modules/katex');
const fonts = readdirSync(join(katex, 'dist/fonts')).filter(f => /^KaTeX_[A-Za-z0-9-]+\.woff2$/.test(f)).sort();
for (const f of fonts) copyFileSync(join(katex, 'dist/fonts', f), join(out, 'fonts', f));
// All supported mobile browsers read WOFF2. Do not ship unused TTF/WOFF fallbacks.
const css = readFileSync(join(katex, 'dist/katex.min.css'), 'utf8').replace(/src:[^;}]+/g, source => {
  const woff = source.match(/url\([^)]*\.woff2\)\s*format\(["']?woff2["']?\)/);
  if (!woff) throw Error('Unexpected font declaration'); return 'src:' + woff[0];
});
writeFileSync(join(out, 'katex.css'), css);
const packages = ['markdown-it', 'katex', 'linkify-it', 'mdurl', 'punycode.js', 'uc.micro', 'entities', 'argparse'];
const licenses = packages.map(name => {
  const path = join(here, 'node_modules', name), p = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
  const license = readdirSync(path).find(f => /^licen[cs]e(?:[-.].*)?$/i.test(f));
  if (!license) throw Error('Missing dependency license: ' + name);
  return `## ${name} ${p.version}\n${readFileSync(join(path, license), 'utf8')}\n`;
}).join('\n');
writeFileSync(join(out, 'LICENSES.txt'), licenses.trimEnd() + '\n');
const vendor = ['vendor/markdown-engine.js', 'vendor/katex.css', 'vendor/LICENSES.txt', 'vendor/precache.js', ...fonts.map(f => 'vendor/fonts/' + f)];
writeFileSync(join(out, 'precache.js'), '// Generated by mobile/build-markup.mjs. Public code/fonts only.\nself.OX_MARKUP_ASSETS = ' + JSON.stringify(vendor.map(f => '/' + f)) + ';\n');
const files = ['index.html', 'app.js', 'ui.js', 'cache.js', 'markdown.js', 'style.css', 'sw.js', 'manifest.webmanifest', 'icon.svg', ...vendor];
writeFileSync(join(here, 'web-assets.mjs'), '// Generated by build-markup.mjs; explicit public source allowlist.\nexport const WEB_ASSETS = ' + JSON.stringify(files, null, 2) + ';\n');
console.log(`Built Markdown/LaTeX assets with ${fonts.length} local fonts; no CDN needed.`);
